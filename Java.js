  async function refreshStats() {
    if (!state.client) return;
    const statMap = [
      ['campana', '#metric-campaigns'],
      ['clientes', '#metric-clients'],
      ['promociones', '#metric-promotions'],
      ['productos', '#metric-products']
    ];

    await Promise.all(statMap.map(async ([key, selector]) => {
      const node = $(selector);
      if (!node) return;
      const tableName = getRealTable(key);
      if (!tableName) { node.textContent = '—'; return; }
      const { count, error } = await state.client
        .from(tableName)
        .select('*', { count: 'exact', head: true });
      node.textContent = error || count === null ? '—' : Number(count).toLocaleString('es');
      if (error) node.title = 'Conteo no disponible: ' + error.message;
    }));
  }

