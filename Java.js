  window.openModal = function openModal() { openForm(null); };

  async function openForm(record = null) {
    if (!state.client) {
      notify('Supabase no está configurado', 'Revisa supabase-config.js.', 'error');
      return;
    }
    const columns = getColumns(state.activeTab);
    const tableName = getRealTable(state.activeTab);
    if (!tableName || !columns.length) {
      notify('No hay esquema disponible', 'No se pudo construir el formulario para esta tabla.', 'error');
      return;
    }

    state.activeRecord = record;
    state.modalBusy = true;
    state.activeColumns = columns;
    const modal = ensureModal();
    const title = $('#crudModalTitle');
    title.replaceChildren();
    title.append(document.createTextNode(record ? 'Editar ' : 'Nuevo '));
    const accent = document.createElement('span');
    accent.textContent = record ? 'registro.' : (state.activeTab === 'campana' ? 'campaign.' : 'registro.');
    title.appendChild(accent);
    const fields = $('#crudFormFields');
    const message = $('#crudFormMessage');
    const form = $('#crudForm');
    const saveButton = $('#crudSaveButton');
    fields.replaceChildren();
    message.textContent = '';
    message.classList.remove('is-error');
    saveButton.disabled = true;
    saveButton.textContent = 'Preparando formulario…';
    modal.classList.add('is-open');
    modal.setAttribute('aria-hidden', 'false');
    document.body.style.overflow = 'hidden';

    const primary = primaryColumns(columns);
    const formColumns = columns.filter(column => {
      if (column.generated) return false;
      if (record && column.primaryKey) return false;
      if (!record && column.primaryKey && autoGenerated(column)) return false;
      if (autoGenerated(column)) return false;
      return true;
    });

    try {
      for (const column of formColumns) {
        const wrapper = document.createElement('div');
        wrapper.className = 'crud-field';
        if (column.dataType === 'text' || column.dataType === 'json' || column.dataType === 'jsonb') wrapper.classList.add('full-width');
        const label = document.createElement('label');
        const inputId = 'crud_field_' + column.name;
        label.htmlFor = inputId;
        label.textContent = labelFor(column.name);
        if (!column.nullable && !column.defaultExpression && !column.identity) {
          const mark = document.createElement('span');
          mark.className = 'field-required';
          mark.textContent = ' *';
          label.appendChild(mark);
        }

        const control = await makeControl(column, record);
        control.id = inputId;
        control.name = column.name;
        control.dataset.column = column.name;
        const isRequired = !column.nullable && !column.defaultExpression && !column.identity;
        if (control.type !== 'checkbox') control.required = isRequired;
        if (control.tagName === 'SELECT' && isRequired) control.required = true;
        if (control.type !== 'checkbox' && control.type !== 'hidden') control.autocomplete = 'off';
        wrapper.append(label, control);

        if (column.foreignKey) {
          const hint = document.createElement('small');
          hint.className = 'field-hint';
          hint.textContent = `Relacionado con ${column.foreignKey.table}.${column.foreignKey.column}`;
          wrapper.appendChild(hint);
        } else if (column.enumValues?.length) {
          const hint = document.createElement('small');
          hint.className = 'field-hint';
          hint.textContent = 'Selecciona uno de los valores permitidos por la base de datos.';
          wrapper.appendChild(hint);
        }
        fields.appendChild(wrapper);
      }
      saveButton.textContent = record ? 'Guardar cambios ↗' : 'Crear registro ↗';
    } catch (error) {
      console.error('Formulario Vantage:', error);
      message.textContent = 'No se pudieron preparar todos los campos: ' + error.message;
      message.classList.add('is-error');
      saveButton.textContent = 'Reintentar';
    } finally {
      state.modalBusy = false;
      saveButton.disabled = false;
      const firstControl = $('input, select, textarea', fields);
      firstControl?.focus({ preventScroll: true });
    }
  }

  async function makeControl(column, record) {
    let control;
    if (Array.isArray(column.enumValues) && column.enumValues.length) {
      control = document.createElement('select');
      if (column.nullable || column.defaultExpression) control.add(new Option('— Seleccionar —', ''));
      else control.add(new Option('Selecciona una opción', ''));
      column.enumValues.forEach(value => control.add(new Option(value, value)));
    } else if (column.foreignKey) {
      control = await makeForeignKeySelect(column, record);
    } else if (column.dataType === 'boolean') {
      control = document.createElement('input');
      control.type = 'checkbox';
    } else if (column.dataType === 'date') {
      control = document.createElement('input');
      control.type = 'date';
    } else if (String(column.dataType).includes('timestamp') || String(column.dataType).includes('time')) {
      control = document.createElement('input');
      control.type = column.dataType === 'time without time zone' ? 'time' : 'datetime-local';
    } else if (isNumericType(column.dataType)) {
      control = document.createElement('input');
      control.type = 'number';
      control.step = ['integer', 'bigint', 'smallint'].includes(column.dataType) ? '1' : 'any';
    } else if (column.dataType === 'json' || column.dataType === 'jsonb') {
      control = document.createElement('textarea');
      control.rows = 3;
      control.placeholder = '{ }';
    } else if (column.dataType === 'text' && (column.name.toLowerCase().includes('descripcion') || column.name.toLowerCase().includes('description') || column.name.toLowerCase().includes('detalle') || column.name.toLowerCase().includes('observacion'))) {
      control = document.createElement('textarea');
      control.rows = 3;
    } else {
      control = document.createElement('input');
      control.type = 'text';
    }

    if (record && record[column.name] !== undefined && record[column.name] !== null) {
      const value = record[column.name];
      if (control.type === 'checkbox') control.checked = Boolean(value);
      else if (control.tagName === 'SELECT') {
        if (![...control.options].some(option => option.value === String(value))) control.add(new Option(String(value), String(value)));
        control.value = String(value);
      } else if (control.type === 'date') control.value = String(value).slice(0, 10);
      else if (control.type === 'datetime-local') control.value = String(value).replace(' ', 'T').slice(0, 16);
      else if (control.tagName === 'TEXTAREA' && typeof value === 'object') control.value = JSON.stringify(value, null, 2);
      else control.value = String(value);
    } else if (control.type === 'checkbox' && column.defaultExpression) {
      control.checked = /true/i.test(String(column.defaultExpression));
    }
    return control;
  }

  async function makeForeignKeySelect(column, record) {
    const fk = column.foreignKey;
    const select = document.createElement('select');
    select.add(new Option('Cargando opciones…', ''));
    try {
      const { data, error } = await state.client.from(fk.table).select('*').order(fk.column, { ascending: true }).limit(500);
      if (error) throw error;
      select.replaceChildren(new Option('— Seleccionar —', ''));
      (data || []).forEach(row => {
        const id = row[fk.column];
        if (id === undefined || id === null) return;
        const display = relationDisplay(row, fk.column, id);
        select.add(new Option(display, String(id)));
      });
      const current = record?.[column.name];
      if (current !== undefined && current !== null && ![...select.options].some(option => option.value === String(current))) {
        select.add(new Option(`Valor actual: ${current}`, String(current)));
      }
    } catch (error) {
      console.warn(`Vantage FK ${fk.table}:`, error.message);
      // Cuando RLS impide leer la tabla relacionada, se permite introducir el ID.
      const input = document.createElement('input');
      input.type = 'text';
      input.inputMode = 'text';
      input.placeholder = `ID de ${fk.table}`;
      input.title = 'No se pudo listar la tabla relacionada; introduce el ID existente.';
      if (record && record[column.name] != null) input.value = String(record[column.name]);
      return input;
    }
    return select;
  }

  function relationDisplay(row, key, id) {
    const labels = ['nombre', 'name', 'titulo', 'title', 'descripcion', 'description', 'razon_social', 'nombre_completo', 'email', 'correo', 'usuario', 'nombre_producto', 'nombre_cliente'];
    for (const name of labels) {
      if (row[name] !== undefined && row[name] !== null && String(row[name]).trim()) return `${row[name]} · #${id}`;
    }
    return `${key}: ${id}`;
  }

  function closeModal() {
    const modal = $('#crudModal');
    if (!modal) return;
    modal.classList.remove('is-open');
    modal.setAttribute('aria-hidden', 'true');
    document.body.style.overflow = '';
    state.activeRecord = null;
  }

  async function saveRecord(event) {
    event.preventDefault();
    if (state.modalBusy) return;
    const button = $('#crudSaveButton');
    const message = $('#crudFormMessage');
    const form = $('#crudForm');
    const tableName = getRealTable(state.activeTab);
    const editing = Boolean(state.activeRecord);
    const columns = state.activeColumns;
    const formControls = $$('[data-column]', form);
    const payload = {};

    message.textContent = '';
    message.classList.remove('is-error');
    button.disabled = true;
    button.textContent = editing ? 'Guardando cambios…' : 'Creando registro…';

    try {
      for (const control of formControls) {
        const name = control.dataset.column;
        const column = columns.find(item => item.name === name);
        if (!column) continue;
        let value;
        if (control.type === 'checkbox') value = control.checked;
        else value = control.value;

        if (control.type === 'checkbox') {
          payload[name] = value;
          continue;
        }

        if (value === '') {
          if (!editing && column.defaultExpression) continue;
          if (column.nullable) { payload[name] = null; continue; }
          if (!control.required) continue;
          throw new Error(`El campo “${labelFor(name)}” es obligatorio.`);
        }

        if (isNumericType(column.dataType)) {
          value = Number(value);
          if (!Number.isFinite(value)) throw new Error(`“${labelFor(name)}” debe ser un número válido.`);
        } else if (column.dataType === 'json' || column.dataType === 'jsonb') {
          try { value = JSON.parse(value); }
          catch { throw new Error(`El campo “${labelFor(name)}” debe contener JSON válido.`); }
        }
        payload[name] = value;
      }

      let response;
      if (editing) {
        const keys = primaryColumns(columns);
        if (!keys.length) throw new Error('No se detectó una clave primaria; no se puede actualizar de forma segura.');
        let query = state.client.from(tableName).update(payload);
        keys.forEach(key => { query = query.eq(key.name, state.activeRecord[key.name]); });
        response = await query;
      } else {
        response = await state.client.from(tableName).insert([payload]);
      }

      if (response.error) throw response.error;
      const savedMessage = editing ? 'Registro actualizado correctamente.' : 'Registro creado correctamente.';
      closeModal();
      notify(savedMessage, `${TABLES[state.activeTab].title} · ${tableName}`);
      await loadTable(state.activeTab);
      await refreshStats();
    } catch (error) {
      console.error('Vantage CRUD save:', error);
      message.textContent = friendlyError(error);
      message.classList.add('is-error');
      notify('No se pudo guardar el registro', error.message || 'Error desconocido', 'error');
    } finally {
      button.disabled = false;
      button.textContent = editing ? 'Guardar cambios ↗' : 'Crear registro ↗';
    }
  }

  async function deleteRecord(record) {
    const tableName = getRealTable(state.activeTab);
    const columns = getColumns(state.activeTab);
    const keys = primaryColumns(columns);
    if (!keys.length) {
      notify('No se puede eliminar', 'No se detectó la clave primaria de esta tabla.', 'error');
      return;
    }

    const rowId = keys.map(key => `${labelFor(key.name)} ${record[key.name]}`).join(' · ');
    const confirmed = window.confirm(`¿Eliminar ${rowId} de ${TABLES[state.activeTab].title}?\n\nEsta acción no se puede deshacer.`);
    if (!confirmed) return;

    try {
      let query = state.client.from(tableName).delete();
      keys.forEach(key => { query = query.eq(key.name, record[key.name]); });
      const { error } = await query;
      if (error) throw error;
      notify('Registro eliminado', rowId);
      await loadTable(state.activeTab);
      await refreshStats();
    } catch (error) {
      console.error('Vantage CRUD delete:', error);
      notify('No se pudo eliminar', error.message || 'Error desconocido', 'error');
    }
  }

  function friendlyError(error) {
    const text = String(error?.message || 'Error desconocido');
    if (/row-level security|row level security/i.test(text)) return `${text} · Revisa las políticas RLS para esta operación y el rol actual.`;
    if (/foreign key constraint/i.test(text)) return `${text} · El valor debe existir en la tabla relacionada.`;
    if (/invalid input value for enum/i.test(text)) return `${text} · Selecciona uno de los valores permitidos por el ENUM.`;
    if (/duplicate key|unique constraint/i.test(text)) return `${text} · Ya existe un registro con ese valor único.`;
    if (/not-null constraint/i.test(text)) return `${text} · Completa todos los campos obligatorios.`;
    return text;
  }

